-- Proof query for SILVER_AP_INVOICES: Silver vs Bronze counts per SOURCE_SYSTEM.
-- Rerun after every change. Expect COUNT_MATCH = TRUE and BAD_STATUS_ROWS = 0 on every row.
USE ROLE SNOWFLAKE_LEARNING_ROLE;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

WITH bronze AS (
    SELECT 'SAP' AS SOURCE_SYSTEM, COUNT(*) AS BRONZE_ROWS FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_SOURCE_DATA.BRONZE_SAP_AP_INVOICES
    UNION ALL
    SELECT 'ORACLE', COUNT(*) FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_SOURCE_DATA.BRONZE_ORACLE_AP_INVOICES
    UNION ALL
    -- Baan is deduplicated on invoice number in Silver (BR-003)
    SELECT 'BAAN', COUNT(DISTINCT BAN_INVOICE_REF) FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_SOURCE_DATA.BRONZE_BAAN_AP_INVOICES
    UNION ALL
    SELECT 'WORKDAY', COUNT(*) FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_SOURCE_DATA.BRONZE_WORKDAY_AP_INVOICES
),
silver AS (
    SELECT SOURCE_SYSTEM,
           COUNT(*) AS SILVER_ROWS,
           SUM(INVOICE_AMOUNT) AS SILVER_AMOUNT,
           COUNT_IF(APPROVAL_STATUS NOT IN ('APPROVED', 'PENDING')) AS BAD_STATUS_ROWS
    FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_PIPELINE_LAB.SILVER_AP_INVOICES
    GROUP BY SOURCE_SYSTEM
)
SELECT COALESCE(s.SOURCE_SYSTEM, b.SOURCE_SYSTEM) AS SOURCE_SYSTEM,
       b.BRONZE_ROWS,
       s.SILVER_ROWS,
       s.SILVER_AMOUNT,
       s.BAD_STATUS_ROWS,
       b.BRONZE_ROWS = s.SILVER_ROWS AS COUNT_MATCH
FROM silver s
FULL OUTER JOIN bronze b ON s.SOURCE_SYSTEM = b.SOURCE_SYSTEM
ORDER BY SOURCE_SYSTEM;
