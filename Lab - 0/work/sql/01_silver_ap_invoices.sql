USE ROLE SNOWFLAKE_LEARNING_ROLE;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

CREATE OR ALTER DYNAMIC TABLE SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_PIPELINE_LAB.SILVER_AP_INVOICES
  TARGET_LAG = '1 hour'
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  REFRESH_MODE = INCREMENTAL
  INITIALIZE = ON_CREATE
  COMMENT = 'Silver AP invoices: SAP + Oracle normalized to a common schema (Lab 0 Demo 1)'
AS
SELECT INVOICE_ID, INVOICE_NUMBER, VENDOR_ID, VENDOR_NAME, INVOICE_DATE, DUE_DATE,
       INVOICE_AMOUNT, CURRENCY_CODE, PAYMENT_TERMS, PO_NUMBER, LINE_DESCRIPTION,
       GL_ACCOUNT, COST_CENTER, APPROVAL_STATUS, CREATED_AT, 'SAP' AS SOURCE_SYSTEM
FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_SOURCE_DATA.BRONZE_SAP_AP_INVOICES
UNION ALL
SELECT INV_ID, INV_NUM, SUPPLIER_ID, SUPPLIER_NAME, INV_DATE, PAYMENT_DUE_DATE,
       TOTAL_AMOUNT, CURRENCY, TERMS_CODE, PURCHASE_ORDER, DESCRIPTION,
       ACCOUNT_CODE, DEPT_CODE,
       CASE UPPER(STATUS) WHEN 'VALIDATED' THEN 'APPROVED' ELSE UPPER(STATUS) END,
       CREATION_DATE, 'ORACLE'
FROM SNOWFLAKE_LEARNING_DB.SAISRISATYA_COCO_SOURCE_DATA.BRONZE_ORACLE_AP_INVOICES;
